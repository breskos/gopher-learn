// Command gendata writes the synthetic data sets of internal/synth as files.
//
//	go run ./internal/cmd/gendata -out ../gopher-learn-data/synthetic
//
// Besides the data it writes a README and a small Go module (package
// synthetic, standard library only) with a catalog of all data sets, a
// reader, examples and a test that checks every file. Run "go test" in the
// output directory to verify the data.
//
// Rows are streamed to disk, so memory use stays small for any size.
package main

import (
	"embed"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"os"
	"path/filepath"
	"strings"

	"github.com/breskos/gopher-learn/internal/synth"
)

// modulePath is the import path of the generated Go module.
const modulePath = "github.com/breskos/gopher-learn-data/synthetic"

//go:embed module/*.tmpl
var moduleFiles embed.FS

func main() {
	out := flag.String("out", "", "output directory (required)")
	seed := flag.Uint64("seed", 1, "random seed; the same seed produces identical files")
	scale := flag.Float64("scale", 1, "multiplier for the default row counts, e.g. 0.1 for small files")
	only := flag.String("only", "", "generate only data sets whose path contains this text (skips README and Go module)")
	flag.Parse()
	if *out == "" || *scale <= 0 {
		flag.Usage()
		os.Exit(2)
	}
	if err := run(*out, *seed, *scale, *only); err != nil {
		log.Fatal(err)
	}
}

func run(out string, seed uint64, scale float64, only string) error {
	var written []synth.Dataset
	var rows []int
	for _, d := range synth.All() {
		if only != "" && !strings.Contains(d.Path, only) {
			continue
		}
		n := max(1, int(float64(d.Rows)*scale))
		path := filepath.Join(out, filepath.FromSlash(d.Path))
		size, err := writeAtomic(path, func(w io.Writer) error { return d.Write(w, n, seed) })
		if err != nil {
			return fmt.Errorf("%s: %w", d.Path, err)
		}
		fmt.Printf("%-40s %9d rows %8.1f MB\n", d.Path, n, float64(size)/(1<<20))
		written = append(written, d)
		rows = append(rows, n)
	}
	if len(written) == 0 {
		return fmt.Errorf("no data set matches %q", only)
	}
	if only != "" {
		return nil // a partial run would leave an incomplete catalog
	}
	return writeModule(out, written, rows, seed, scale)
}

// writeModule writes the README and the Go module next to the data.
func writeModule(out string, sets []synth.Dataset, rows []int, seed uint64, scale float64) error {
	files := map[string]func(io.Writer) error{
		"README.md":  func(w io.Writer) error { return writeReadme(w, sets, rows, seed, scale) },
		"catalog.go": func(w io.Writer) error { return writeCatalog(w, sets, rows) },
		"go.mod": func(w io.Writer) error {
			_, err := fmt.Fprintf(w, "module %s\n\ngo 1.24\n", modulePath)
			return err
		},
	}
	templates, err := moduleFiles.ReadDir("module")
	if err != nil {
		return err
	}
	for _, e := range templates {
		content, err := moduleFiles.ReadFile("module/" + e.Name())
		if err != nil {
			return err
		}
		files[strings.TrimSuffix(e.Name(), ".tmpl")] = func(w io.Writer) error {
			_, err := w.Write(content)
			return err
		}
	}
	for name, fn := range files {
		if _, err := writeAtomic(filepath.Join(out, name), fn); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
	}
	return nil
}

func fileFormat(d synth.Dataset) string {
	switch {
	case d.Format == synth.CSV:
		return "CSV"
	case strings.HasSuffix(d.Path, ".svm"):
		return "LIBSVM"
	default:
		return "Phrase"
	}
}

func writeCatalog(w io.Writer, sets []synth.Dataset, rows []int) error {
	var b strings.Builder
	b.WriteString("// Code generated by gopher-learn/internal/cmd/gendata. DO NOT EDIT.\n\npackage synthetic\n\n")
	b.WriteString("// Datasets lists every data set in this folder, grouped by purpose.\nvar Datasets = []Dataset{\n")
	for i, d := range sets {
		fmt.Fprintf(&b, "\t{\n\t\tPath:        %q,\n\t\tFolder:      %q,\n\t\tDescription: %q,\n", d.Path, d.Folder(), d.Description)
		fmt.Fprintf(&b, "\t\tTask:        %q,\n\t\tFormat:      %s,\n\t\tRows:        %d,\n", d.Task.String(), fileFormat(d), rows[i])
		if d.Format == synth.CSV {
			fmt.Fprintf(&b, "\t\tHeader:      %#v,\n\t\tTarget:      %q,\n", d.Header, d.Target)
			if len(d.Ignore) > 0 {
				fmt.Fprintf(&b, "\t\tIgnore:      %#v,\n", d.Ignore)
			}
			if d.Comma != 0 {
				fmt.Fprintf(&b, "\t\tComma:       %q,\n", d.Comma)
			}
		}
		for _, flag := range []struct {
			name string
			on   bool
		}{{"Ordered", d.Ordered}, {"Applied", d.Applied}, {"AllowMissing", d.AllowMissing}} {
			if flag.on {
				fmt.Fprintf(&b, "\t\t%s: true,\n", flag.name)
			}
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("format catalog: %w", err)
	}
	_, err = w.Write(src)
	return err
}

