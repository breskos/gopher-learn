func writeReadme(w io.Writer, sets []synth.Dataset, rows []int, seed uint64, scale float64) error {
	var b strings.Builder
	b.WriteString("# Synthetic data sets for gopher-learn\n\n")
	b.WriteString("All data in this folder is generated; it contains no third-party data. ")
	b.WriteString("Every data set has a known structure, so you can tell how well a model should do. ")
	b.WriteString("Data sets marked *sensor* model real sensors with simple physical and behavioral models; they look like sensor data but are not measurements.\n\n")
	b.WriteString("The folders are named after what the data is for:\n\n| Folder | Purpose |\n| --- | --- |\n")
	for _, f := range synth.Folders {
		fmt.Fprintf(&b, "| [%s](#%s) | %s |\n", f.Name, f.Name, f.Purpose)
	}
	b.WriteString("\n## Check and read the data in Go\n\n")
	b.WriteString("This folder is a Go module (`" + modulePath + "`, standard library only). ")
	b.WriteString("[catalog.go](catalog.go) lists every file with its columns and purpose, [reader.go](reader.go) reads any of them, ")
	b.WriteString("[example_test.go](example_test.go) shows one reader per folder, and [synthetic_test.go](synthetic_test.go) checks every file:\n\n")
	b.WriteString("```\ngo test ./...\n```\n\n")
	fmt.Fprintf(&b, "The files are reproducible: in the [gopher-learn](https://github.com/breskos/gopher-learn) repository run\n\n```\ngo run ./internal/cmd/gendata -out <this folder>")
	if seed != 1 {
		fmt.Fprintf(&b, " -seed %d", seed)
	}
	if scale != 1 {
		fmt.Fprintf(&b, " -scale %g", scale)
	}
	b.WriteString("\n```\n\nThe same seed produces identical files.\n")

	for _, f := range synth.Folders {
		var idx []int
		for i, d := range sets {
			if d.Folder() == f.Name {
				idx = append(idx, i)
			}
		}
		if len(idx) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n## %s\n\n%s\n\n| File | Task | Rows | Kind |\n| --- | --- | --- | --- |\n", f.Name, f.Purpose)
		for _, i := range idx {
			d := sets[i]
			kind := "benchmark"
			if d.Applied {
				kind = "sensor"
			}
			fmt.Fprintf(&b, "| [%s](%s) | %v | %d | %s |\n", d.Path, d.Path, d.Task, rows[i], kind)
		}
		if u, ok := usage[f.Name]; ok {
			fmt.Fprintf(&b, "\nWith gopher-learn:\n\n```go\n%s\n```\n", u)
		}
		for _, i := range idx {
			d := sets[i]
			fmt.Fprintf(&b, "\n### %s\n\n%s\n", d.Path, d.Description)
			if d.Format == synth.CSV {
				fmt.Fprintf(&b, "\nColumns: `%s`. Target: `%s`.", strings.Join(d.Header, "`, `"), d.Target)
				if len(d.Ignore) > 0 {
					fmt.Fprintf(&b, " Ignore: `%s`.", strings.Join(d.Ignore, "`, `"))
				}
				if d.Comma != 0 {
					fmt.Fprintf(&b, " Delimiter: `%c`.", d.Comma)
				}
				if d.Ordered {
					b.WriteString(" Read in order.")
				}
				b.WriteString("\n")
			}
		}
	}
	_, err := io.WriteString(w, b.String())
	return err
}

// writeAtomic writes to a temporary file next to path and renames it, so an
// interrupted run never leaves a half-written file behind.
func writeAtomic(path string, fn func(io.Writer) error) (size int64, err error) {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return 0, err
	}
	f, err := os.CreateTemp(filepath.Dir(path), filepath.Base(path)+".tmp*")
	if err != nil {
		return 0, err
	}
	defer func() {
		if err != nil {
			_ = f.Close()
			_ = os.Remove(f.Name())
		}
	}()
	if err = fn(f); err != nil {
		return 0, err
	}
	info, err := f.Stat()
	if err != nil {
		return 0, err
	}
	if err = f.Chmod(0o644); err != nil {
		return 0, err
	}
	if err = f.Close(); err != nil {
		return 0, err
	}
	return info.Size(), os.Rename(f.Name(), path)
}
